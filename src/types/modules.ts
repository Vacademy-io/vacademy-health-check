// Institute Modules & Configuration — wire shapes (spec §12, snake_case).
// The catalogue and nav manifest are served by admin_core; nothing here is a
// hard-coded module list.

export interface CatalogGoverns {
  nav: string[];
  widgets: string[];
  quick_actions: string[];
  assistant_groups: string[];
  setup_steps: string[];
  routes: string[];
}

export interface CatalogFeature {
  key: string;
  label: string;
  description: string | null;
  default_on: boolean;
  governs: CatalogGoverns;
  setting_keys: string[];
}

export interface CatalogModule {
  key: string;
  label: string;
  description: string | null;
  /** Sidebar rail category the module lives under. */
  rail: string | null;
  /** Core modules are always on and cannot be switched off. */
  core: boolean;
  features: CatalogFeature[];
}

export interface CapabilityCatalog {
  version: number;
  modules: CatalogModule[];
}

export interface RoleDefaults {
  ADMIN: boolean;
  TEACHER: boolean;
}

export interface NavCategory {
  id: string;
  label: string;
  default_visible: boolean;
  order: number;
  /** The category the admin app lands on when nothing else applies. */
  is_default_landing: boolean;
}

export interface NavSubTab {
  id: string;
  label: string;
  route: string | null;
  order: number;
  admin_only: boolean;
  default_visible: RoleDefaults;
}

export interface NavTab {
  id: string;
  label: string;
  category: string;
  route: string | null;
  order: number;
  default_visible: RoleDefaults;
  sub_tabs: NavSubTab[];
}

/** Generated by the admin app from getSidebarItemsData() + role defaults (spec §12.1). */
export interface NavManifest {
  generated_at: string | null;
  categories: NavCategory[];
  /** Never shown to a non-admin, whatever the role's settings say. */
  always_admin_only_tab_ids: string[];
  /** A non-admin gets these tabs only when the role's blob switches them on (visible: true). */
  non_admin_opt_in_tab_ids: string[];
  /** Non-admins never get these tabs' admin_only sub-tabs, even when switched on. */
  admin_only_sub_tabs_never_opt_in_tab_ids: string[];
  /** Sub-Organizations module grant (role blob flag) — see nav-preview.ts. */
  sub_org_module: NavSubOrgModule | null;
  tabs: NavTab[];
}

export interface NavSubOrgModule {
  tab_id: string;
  sub_tab_id: string;
  /** Dotted path inside the role blob, e.g. "subOrganizations.moduleEnabled". */
  role_setting: string;
}

/** GET /admin-core-service/capabilities/v1/catalog */
export interface CatalogResponse {
  catalog: CapabilityCatalog | null;
  nav: NavManifest | null;
}

export type ModuleMode = "LEGACY" | "MANAGED";

export interface EntitlementRow {
  key: string;
  enabled: boolean;
  expires_at: string | null;
  note: string | null;
  updated_by: string | null;
  updated_at: string | null;
}

export interface ResolvedEntitlements {
  modules: Record<string, boolean>;
  features: Record<string, boolean>;
}

/** GET/PUT /super-admin/v1/institutes/{id}/modules */
export interface InstituteModules {
  institute_id: string;
  mode: ModuleMode;
  mode_updated_by: string | null;
  mode_updated_at: string | null;
  catalog_version: number | null;
  entitlements: EntitlementRow[];
  /** What MANAGED mode would apply, even while LEGACY. */
  resolved: ResolvedEntitlements;
}

export interface EntitlementChange {
  key: string;
  enabled: boolean;
  expires_at?: string | null;
  note?: string | null;
}

export interface UpdateInstituteModulesRequest {
  mode?: ModuleMode;
  changes: EntitlementChange[];
  reason: string;
}

export interface PageResponse<T> {
  content: T[];
  total_elements: number;
  total_pages: number;
  number: number;
  size: number;
}

export interface ModuleHistoryEntry {
  id: string;
  /** Module/feature key, or `_mode` for a mode change. */
  key: string;
  /** JSON strings, e.g. {"enabled":true,"expires_at":null}. */
  old_value: string | null;
  new_value: string | null;
  reason: string | null;
  /** Note stored with the change, when any. */
  note: string | null;
  actor_user_id: string | null;
  created_at: string | null;
}

export interface ModulesOverviewEntry {
  mode: ModuleMode;
  /** Includes core; computed with the MANAGED rule even while LEGACY. */
  enabled_modules: string[];
}

export type ModulesOverview = Record<string, ModulesOverviewEntry>;

export interface ModulePreset {
  key: string;
  name: string;
  description: string | null;
  modules: string[];
  updated_by: string | null;
  updated_at: string | null;
}

export interface SaveModulePresetRequest {
  name: string;
  description: string;
  modules: string[];
}

export interface ApplyPresetResult {
  applied: string[];
  failed: Array<{ institute_id: string; error: string }>;
}

export type InstituteRoleKind = "ADMIN" | "TEACHER" | "SYSTEM" | "CUSTOM";

/** auth_service GET /super-admin/v1/institutes/{id}/roles */
export interface InstituteRole {
  role_id: string;
  role_name: string;
  kind: InstituteRoleKind;
  user_count: number | null;
}

/** GET/PUT /super-admin/v1/institutes/{id}/display-settings?role_key= */
export interface RoleDisplaySettings {
  role_key: string;
  /** Stored blob for that role, or null when the institute never saved one. */
  data: Record<string, unknown> | null;
  version: string | null;
}

export interface SaveDisplaySettingsRequest {
  /** null removes the role's blob (the admin app falls back to its defaults). */
  data: Record<string, unknown> | null;
  /** Required by the server (400 when missing): the version from the last GET. */
  expected_version: string;
  reason: string;
}

export type SettingSource = "TENANT" | "PLATFORM";

export interface SettingHistoryEntry {
  id: string;
  setting_key: string;
  actor_user_id: string | null;
  source: SettingSource | string;
  created_at: string | null;
  reason: string | null;
}

export interface SettingHistoryDetail extends SettingHistoryEntry {
  old_value: string | null;
  new_value: string | null;
}

/** POST …/settings/history/{hid}/restore */
export interface RestoreSettingResult {
  restored_from: string;
  setting_key: string;
  /** false when the key already held that value (no new history row). */
  changed: boolean;
}
